COLS, TILE = 16, 32
MAX_GLYPHS = 256  # 16 rows x 16 cols -> 512x512 texture


def fetch(cp, dst):
    url = f"https://cdn.jsdelivr.net/gh/jdecked/twemoji@15.1.0/assets/72x72/{cp:x}.png"
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req, timeout=30) as r:
        data = r.read()
    with open(dst, "wb") as f:
        f.write(data)


def main():
    import struct

    entries = list(dict.fromkeys(EMOJI_BASE + EMOJI_EXTRA))[:MAX_GLYPHS]

    def grab(item):
        i, cp = item
        tmp = os.path.join(HERE, "tools", f"tmp_emoji_{i:03d}.png")
        try:
            fetch(cp, tmp)
            img = Image.open(tmp).convert("RGBA")
            bg = Image.new("RGBA", img.size, (255, 255, 255, 255))
            bg.alpha_composite(img)
            return bg.resize((TILE, TILE), Image.LANCZOS)
        except Exception as e:
            print(f"skip {cp:x}: {e}")
            return None
        finally:
            try:
                os.remove(tmp)
            except OSError:
                pass

    with ThreadPoolExecutor(max_workers=8) as ex:
        images = list(ex.map(grab, enumerate(entries)))

    rows = 8
    while rows * COLS < len(entries):
        rows <<= 1
    atlas_w, atlas_h = COLS * TILE, rows * TILE

    atlas = Image.new("RGBA", (atlas_w, atlas_h), (255, 255, 255, 255))
    for i, img in enumerate(images):
        if img is None:
            continue
        x = (i % COLS) * TILE
        y = (i // COLS) * TILE
        atlas.paste(img, (x, y))

    # Tile the atlas in the PICA200 layout (tex3ds permutation, ABGR texels).
    sys.path.insert(0, r"e:/pythonserver/pythonserver2/1.0")
    from non_static.imgconv import _tile_rgba8
    data = _tile_rgba8(atlas, atlas_w, atlas_h)

    with open(os.path.join(HERE, "data", "emoji.bin"), "wb") as f:
        f.write(struct.pack("<HH", atlas_w, atlas_h))
        f.write(data)

    with open(os.path.join(HERE, "source", "emoji_map.h"), "w", encoding="utf-8") as f:
        f.write("// Generated by tools/make_emoji_atlas.py - emoji atlas tile map.\n")
        f.write("#pragma once\n\n")
        f.write(f"#define EMOJI_COUNT {len(entries)}\n")
        f.write("#define EMOJI_TILE 32\n")
        f.write("#define EMOJI_COLS 16\n\n")
        f.write("typedef struct { unsigned int cp; unsigned char idx; } EmojiMap;\n")
        f.write("static const EmojiMap emoji_map[EMOJI_COUNT] = {\n")
        for i, cp in enumerate(entries):
            f.write(f"    {{ 0x{cp:X}, {i} }},\n")
        f.write("};\n")

    print(f"wrote data/emoji.bin ({atlas_w}x{atlas_h}, {len(data) + 4} bytes) and "
          f"source/emoji_map.h ({len(entries)} emoji)")


if __name__ == "__main__":
    main()
